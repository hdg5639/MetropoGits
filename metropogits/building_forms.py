def building_parts(building):
    variant = 0x811C9DC5
    for character in building["entityId"]:
        variant = ((variant ^ ord(character)) * 0x01000193) & 0xFFFFFFFF
    form = FORMS.get(building["archetype"], GENERIC_FORMS[variant % 4])
    w, h, d = building["width"], building["height"], building["depth"]
    return [
        dict(
            x=building["x"] + x * w,
            y=y * h,
            z=building["z"] + z * d,
            width=pw * w,
            height=ph * h,
            depth=pd * d,
            shade=shade,
        )
        for x, y, z, pw, ph, pd, shade in form
    ]
